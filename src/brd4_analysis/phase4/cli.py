"""Phase 4 CLI: run the adversarial battery and write deterministic outputs.

    python -m brd4_analysis.phase4.cli battery --out experiments/phase4/adversarial_screen_v1

Writes ``results.json`` (full per-case record, LF endings, sorted keys),
``FINDINGS.md`` (generated summary table) and ``manifest.json`` (artifact
hashes). Scientific outputs are deterministic; whole-file bytes are
reproducible when the recorded environment metadata is unchanged. No
timestamps are embedded.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import stat
import tempfile
from pathlib import Path

from brd4_analysis.constants import PROJECT_ROOT
from brd4_analysis.phase4.battery import run_battery, summary_table
from brd4_analysis.phase4.evaluate import load_context

PHASE4_OUTPUT_ROOT = PROJECT_ROOT / "experiments" / "phase4"
ARTIFACT_NAMES = ("results.json", "FINDINGS.md", "manifest.json")
# Python reports descriptor-relative support for os.rename rather than its
# higher-level os.replace alias on supported POSIX systems. These functions
# are the complete set used by the protected writer.
_DIRFD_FUNCTIONS = (os.open, os.mkdir, os.stat, os.unlink, os.rename)
_POSIX_DIRFD = (
    os.name == "posix"
    and hasattr(os, "O_DIRECTORY")
    and hasattr(os, "O_NOFOLLOW")
    and all(function in os.supports_dir_fd for function in _DIRFD_FUNCTIONS)
)


def _gate_columns(results):
    seen = []
    for case in results["cases"]:
        for gate in case["gates"]:
            if gate not in seen:
                seen.append(gate)
    return seen


def findings_markdown(results: dict) -> str:
    gates = _gate_columns(results)
    check_names = [
        name for name in results["cases"][0]["candidate_checks"]
    ]
    lines = [
        "<!-- GENERATED by brd4_analysis.phase4.cli battery; do not edit by hand -->",
        "",
        "# Phase 4 adversarial screen — generated findings",
        "",
        f"Battery revision: `{results['battery_revision']}` "
        f"({results['design_status']}).",
        "",
        "Each row is a fixed deterministic synthetic transform of the committed "
        "Boltz-2.2.1 prediction (or a control). `gates` columns are the five "
        "registered Phase 3 acceptance gates; `failed proposals` lists "
        "exploratory, non-registered candidate checks that rejected the case. "
        "An accepted non-control is an accepted synthetic variant under these "
        "gates, not an empirical model false-positive rate or a predictive-"
        "accuracy estimate.",
        "",
        "| case | family | " + " | ".join(gates) + " | all gates | failed proposals |",
        "|---|---|" + "---|" * (len(gates) + 2),
    ]
    for row in summary_table(results):
        case = next(c for c in results["cases"] if c["name"] == row["name"])
        gate_cells = " | ".join("PASS" if case["gates"][g] else "FAIL" for g in gates)
        proposals = ", ".join(row["failed_candidate_checks"]) or "-"
        verdict = "PASS" if row["harness_success"] else "FAIL"
        lines.append(
            f"| `{row['name']}` | {row['family']} | {gate_cells} | {verdict} | {proposals} |"
        )
    lines += [
        "",
        "## Candidate-check values",
        "",
        "| case | " + " | ".join(check_names) + " |",
        "|---|" + "---|" * len(check_names),
    ]
    for case in results["cases"]:
        cells = " | ".join(
            f"{case['candidate_checks'][c]['value']:.4g}"
            + ("" if case["candidate_checks"][c]["pass"] else " **FAIL**")
            for c in check_names
        )
        lines.append(f"| `{case['name']}` | {cells} |")
    lines.append("")
    return "\n".join(lines)


def _allowed_output_root() -> Path:
    """The lexical Phase 4 output root, rejected if it contains an alias."""
    root = Path(os.path.abspath(PHASE4_OUTPUT_ROOT))
    if root.is_symlink() or root.resolve(strict=False) != root:
        raise ValueError("Phase 4 output root must not traverse a symlink")
    return root


def battery_output_dir(path: Path) -> Path:
    """Constrain a battery output directory without following aliases.

    Phase 4 may deliberately regenerate its own artifacts, but must never
    write through a symlink or into the frozen Phase 2/3 evidence area.
    """
    raw = Path(path)
    if ".." in raw.parts:
        raise ValueError("Battery output path must not contain '..'")
    lexical = Path(os.path.abspath(raw if raw.is_absolute() else PROJECT_ROOT / raw))
    root = _allowed_output_root()
    if lexical == root or not lexical.is_relative_to(root):
        raise ValueError("Battery output must be a child of experiments/phase4")
    resolved = lexical.resolve(strict=False)
    if resolved != lexical:
        raise ValueError("Battery output path must not traverse a symlink")
    if lexical.exists() and not lexical.is_dir():
        raise ValueError("Battery output path is not a directory")
    return lexical


class _ArtifactWriter:
    """Create fresh artifact files and replace their directory entries.

    Atomic replacement prevents truncation of a pre-existing hard-linked
    inode. On supported POSIX systems the output directory is opened as a
    descriptor for the whole battery and all creates/replacements are made
    relative to that descriptor, so replacing the directory name with a
    symlink cannot redirect a completed battery outside its pinned inode.
    The portable fallback used on Windows keeps lexical confinement and
    atomic inode replacement, but Python exposes no descriptor-relative
    rename there, so it cannot claim the same post-validation race
    guarantee.
    """

    def __init__(self, out_dir: Path):
        self.out_dir = out_dir
        self._dir_fd = None
        self._counter = 0

    def __enter__(self):
        if _POSIX_DIRFD:
            self._dir_fd = self._open_canonical_directory(self.out_dir)
            self._validate_artifacts_fd()
        elif os.name == "posix":
            raise RuntimeError(
                "POSIX descriptor-relative artifact writes are unavailable"
            )
        else:
            self.out_dir.mkdir(parents=True, exist_ok=True)
            self._validate_portable_directory()
            self._validate_artifacts_path()
        return self

    def __exit__(self, exc_type, exc, traceback):
        if self._dir_fd is not None:
            os.close(self._dir_fd)
            self._dir_fd = None
        return False

    @staticmethod
    def _open_canonical_directory(path: Path) -> int:
        flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
        try:
            fd = os.open(path.anchor, flags)
            for part in path.parts[1:]:
                try:
                    os.mkdir(part, mode=0o777, dir_fd=fd)
                except FileExistsError:
                    pass
                child = os.open(part, flags, dir_fd=fd)
                os.close(fd)
                fd = child
            return fd
        except OSError as exc:
            try:
                os.close(fd)
            except (OSError, UnboundLocalError):
                pass
            raise ValueError(f"Battery output directory is unsafe: {path}") from exc

    def _validate_artifacts_fd(self) -> None:
        for name in ARTIFACT_NAMES:
            try:
                mode = os.stat(
                    name, dir_fd=self._dir_fd, follow_symlinks=False
                ).st_mode
            except FileNotFoundError:
                continue
            if stat.S_ISLNK(mode):
                raise ValueError(f"Refusing to overwrite symlinked artifact {name}")
            if not stat.S_ISREG(mode):
                raise ValueError(f"Battery artifact destination is not a file: {name}")

    def _validate_portable_directory(self) -> None:
        if (
            self.out_dir.is_symlink()
            or self.out_dir.resolve(strict=False) != self.out_dir
            or not self.out_dir.is_dir()
        ):
            raise ValueError("Battery output directory is unsafe")

    def _validate_artifacts_path(self) -> None:
        for name in ARTIFACT_NAMES:
            path = self.out_dir / name
            if path.is_symlink():
                raise ValueError(f"Refusing to overwrite symlinked artifact {path}")
            if path.exists() and not path.is_file():
                raise ValueError(f"Battery artifact destination is not a file: {path}")

    def _write_fd(self, name: str, data: bytes) -> None:
        while True:
            self._counter += 1
            temp_name = f".{name}.tmp.{os.getpid()}.{self._counter}"
            try:
                temp_fd = os.open(
                    temp_name,
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                    0o666,
                    dir_fd=self._dir_fd,
                )
                break
            except FileExistsError:
                continue
        try:
            with os.fdopen(temp_fd, "wb") as temp:
                temp.write(data)
                temp.flush()
                os.fsync(temp.fileno())
            os.rename(
                temp_name,
                name,
                src_dir_fd=self._dir_fd,
                dst_dir_fd=self._dir_fd,
            )
            temp_name = None
            os.fsync(self._dir_fd)
        finally:
            if temp_name is not None:
                try:
                    os.unlink(temp_name, dir_fd=self._dir_fd)
                except FileNotFoundError:
                    pass

    def _write_portable(self, name: str, data: bytes) -> None:
        self._validate_portable_directory()
        self._validate_artifacts_path()
        target = self.out_dir / name
        temp_name = None
        try:
            with tempfile.NamedTemporaryFile(
                "wb", dir=self.out_dir, prefix=f".{name}.", delete=False
            ) as temp:
                temp.write(data)
                temp.flush()
                os.fsync(temp.fileno())
                temp_name = temp.name
            os.replace(temp_name, target)
            temp_name = None
        finally:
            if temp_name is not None:
                Path(temp_name).unlink(missing_ok=True)

    def write(self, name: str, data: bytes) -> None:
        if name not in ARTIFACT_NAMES:
            raise ValueError(f"Unexpected battery artifact {name!r}")
        if self._dir_fd is not None:
            self._write_fd(name, data)
        else:
            self._write_portable(name, data)


def cmd_battery(out_dir: Path) -> int:
    out_dir = battery_output_dir(out_dir)
    with _ArtifactWriter(out_dir) as writer:
        ctx = load_context()
        results = run_battery(ctx)
        result_bytes = (
            json.dumps(results, indent=2, sort_keys=True, allow_nan=False) + "\n"
        ).encode()
        findings_bytes = findings_markdown(results).encode()
        writer.write("results.json", result_bytes)
        writer.write("FINDINGS.md", findings_bytes)
        manifest = {
            "schema_version": 1,
            "battery_revision": results["battery_revision"],
            "output_artifacts_sha256": {
                "results.json": hashlib.sha256(result_bytes).hexdigest(),
                "FINDINGS.md": hashlib.sha256(findings_bytes).hexdigest(),
            },
            "input_provenance": results["provenance"],
            "phase4_source_sha256_LF": results["phase4_source_sha256_LF"],
        }
        writer.write(
            "manifest.json",
            (json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n").encode(),
        )
    accepted = [
        c["name"] for c in results["cases"]
        if c["harness_success"] and not c["name"].startswith("control_")
    ]
    passed_controls = all(
        c["harness_success"]
        for c in results["cases"]
        if c["name"].startswith("control_")
    )
    print(f"cases: {len(results['cases'])}")
    print(f"controls all pass: {passed_controls}")
    print(f"accepted non-control synthetic variants: {len(accepted)}")
    for name in accepted:
        print(f"  accepted synthetic variant: {name}")
    return 0 if passed_controls else 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="brd4_analysis.phase4.cli")
    sub = parser.add_subparsers(dest="command", required=True)
    battery = sub.add_parser("battery", help="run the adversarial battery")
    battery.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    if args.command == "battery":
        return cmd_battery(args.out)
    raise AssertionError(args.command)


if __name__ == "__main__":
    raise SystemExit(main())
